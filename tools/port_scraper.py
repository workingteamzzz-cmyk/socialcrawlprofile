"""Make crawler/apiscraper/engine.py from the team's Colab script (social_scraper_advanced_v58_en.py):

    python tools/port_scraper.py path/to/social_scraper_advanced_vNN_en.py

The team's code stays as it is — scraping, cleaning, sentiment/emotion, the Excel layout. Only these are changed:
  1. ipywidgets / IPython.display / google.colab are replaced by stand-ins (colab_shim) driven by the dashboard;
  2. no pip installs at run time (openpyxl, transformers are installed with the app, or not used);
  3. no Google Drive: files go to the app's Exports folder (OUT_DIR); checkpoints to the app's data folder;
  4. no password box (the dashboard's sign-in and roles protect it);
  5. a Stop flag (the dashboard's Stop button) that ends the run like the credit cap does — data so far is kept;
  6. the AI language models are off by default (a 4 GB server cannot load them); the team's lexicon analysis is used;
  7. the form display at the end of the script is left out (the dashboard shows the form).
Every edit must match exactly once, so a new version that changed those places stops here instead of being ported
wrongly.
"""
import re
import sys


def port(src: str) -> str:
    s = src

    def sub(old: str, new: str, count: int = 1):
        nonlocal s
        n = s.count(old)
        if n != count:
            raise SystemExit(f"port_scraper: expected {count}x, found {n}x: {old[:80]!r}")
        s = s.replace(old, new)

    sub('''import subprocess, sys
try:
    import openpyxl
except ImportError:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "openpyxl"])
''', '''import subprocess, sys, os
import openpyxl  # noqa: F401  (installed with the app)
''')
    sub('''import ipywidgets as widgets
from IPython.display import display
from google.colab import files
''', '''from .colab_shim import widgets, display, files   # the Colab form is driven by the dashboard
''')
    sub('''class BudgetExceeded(Exception):
    pass
''', '''class BudgetExceeded(Exception):
    pass

STOP = {"on": False}            # the dashboard's Stop button: ends the run like the credit cap (data so far is kept)
OUT_DIR = "."                   # where the Excel/CSV go (the app's Exports folder)
AI_ALLOWED = False              # the AI language models need ~2 GB + a GPU; the team's lexicon analysis is used
_out_path = os.path.join        # (on_click has its own local "import os", so it cannot use the module's os)
''')
    sub('''    url = a[0] if a else k.get("url", "")
    is_twitter = _TWITTER_PROVIDER_HOST in str(url)
''', '''    url = a[0] if a else k.get("url", "")
    if STOP["on"]:
        raise BudgetExceeded("stopped from the dashboard")
    is_twitter = _TWITTER_PROVIDER_HOST in str(url)
''')
    sub('''    import os
    from google.colab import drive
    drive.mount("/content/drive")''', '''    raise RuntimeError("Google Drive is not used on the server (files go to Exports)")
    import os
    from google.colab import drive
    drive.mount("/content/drive")''')
    sub('''NLP_MODE = {"mode": "ai"}''', '''NLP_MODE = {"mode": "lexicon"}''')
    sub('''    if _NLP["tried"]:
        return _NLP["ok"]
    _NLP["tried"] = True
''', '''    if _NLP["tried"]:
        return _NLP["ok"]
    _NLP["tried"] = True
    if not AI_ALLOWED:
        _NLP["ok"] = False
        return False
''')
    pw = re.search(r'\n        if hashlib\.sha256\(pw_w\.value\.encode\(\)\)\.hexdigest\(\) != _PW_HASH:\n'
                   r'            print\("[^"]*"\); return\n', s)
    if not pw:
        raise SystemExit("port_scraper: the password check in on_click was not found")
    s = s[:pw.start()] + "\n        # (password box: replaced by the dashboard's sign-in and roles)\n" + s[pw.end():]
    sub('''            xp = base + ".xlsx"''', '''            xp = _out_path(OUT_DIR, base + ".xlsx")''')
    sub('''            df.to_csv(base + ".csv", index=False); saved.append(base + ".csv")''',
        '''            df.to_csv(_out_path(OUT_DIR, base + ".csv"), index=False); saved.append(_out_path(OUT_DIR, base + ".csv"))''')
    sub('''        print("To stop early: press the ■ (interrupt) button or Runtime → Interrupt execution. Data collected so far is still saved.")''',
        '''        print("To stop early: press Stop on the dashboard. Data collected so far is still saved (Exports).")''')
    cut = s.find("\nbtn.on_click(on_click)\n")
    if cut < 0:
        raise SystemExit("port_scraper: 'btn.on_click(on_click)' not found")
    s = s[:cut] + "\n# (the form display that followed here is the dashboard's API Scraper page)\n"
    header = ('# Generated by tools/port_scraper.py from the team\'s Social Scraper (Colab) — do not edit by hand;\n'
              '# change the team\'s script and run the tool again.\n')
    return header + s


if __name__ == "__main__":
    src = open(sys.argv[1], encoding="utf-8").read()
    out = sys.argv[2] if len(sys.argv) > 2 else "crawler/apiscraper/engine.py"
    with open(out, "w", encoding="utf-8") as f:
        f.write(port(src))
    print(f"wrote {out}")
